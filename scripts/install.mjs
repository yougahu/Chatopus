#!/usr/bin/env node
/** Install this checkout into a private, external deployment directory. */
import { spawn, spawnSync } from 'node:child_process';
import { accessSync, chmodSync, constants, lstatSync, mkdirSync, readFileSync, realpathSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { basename, delimiter, dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = realpathSync(fileURLToPath(new URL('..', import.meta.url)));
const marker = '# Generated by Chatopus installer.';
const quote = value => "'" + value.replaceAll("'", "'\\''") + "'";
const help = `Chatopus 基础安装（Linux / macOS）

用法：node scripts/install.mjs [选项]
  --deploy-dir <目录>  私有配置和运行目录，默认 ~/.local/share/chatopus
  --skip-deps          复用当前源码已安装的依赖，不运行 npm ci
  --start-admin        安装成功后在前台启动管理后台，Ctrl-C 停止
  --port <端口>       管理后台端口，默认 8092；0 表示自动选择
  --help              显示帮助

需要 Node.js 22.16+（22.x）或 24+、npm 和 ripgrep（rg）。
保留已有配置、密钥及状态；Router / Worker 可稍后在后台配置。
`;

function stat(path) {
  try { return lstatSync(path); } catch (error) { if (error.code === 'ENOENT') return undefined; throw error; }
}

// Resolve existing ancestors too, so a symlink cannot put private files in the checkout.
function canonical(path) {
  try { return realpathSync(path); } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    return join(canonical(dirname(path)), basename(path));
  }
}

function contains(parent, child) {
  const path = relative(parent, child);
  return path === '' || (!isAbsolute(path) && path !== '..' && !path.startsWith('..' + sep));
}

function executable(name) {
  for (const directory of (process.env.PATH ?? '').split(delimiter)) {
    const path = resolve(directory, name);
    try { accessSync(path, constants.X_OK); if (stat(path)?.isDirectory() === false) return path; } catch {}
  }
  throw new Error(`缺少 ${name}，请先安装并加入 PATH，再重新运行安装脚本。`);
}

function run(program, args, cwd, env) {
  const result = spawnSync(program, args, { cwd, env, stdio: 'inherit' });
  if (result.error || result.status !== 0) throw new Error(`${basename(program)} ${args[0]} 执行失败，请根据上方输出排查后重试。`);
}

function createPrivate(path, content) {
  if (!stat(path)) writeFileSync(path, content, { flag: 'wx', mode: 0o600 });
  chmodSync(path, 0o600);
}

async function main() {
  const args = process.argv.slice(2);
  if (args.includes('--help')) { console.log(help); return; }
  let deployment = join(homedir(), '.local', 'share', 'chatopus'), skipDeps = false, startAdmin = false, port = '8092';
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--skip-deps') skipDeps = true;
    else if (arg === '--start-admin') startAdmin = true;
    else if (arg === '--deploy-dir' || arg === '--port') {
      const value = args[++i];
      if (!value || value.startsWith('--')) throw new Error(`${arg} 缺少参数；使用 --help 查看用法。`);
      if (arg === '--deploy-dir') deployment = value;
      else port = value;
    } else throw new Error(`未知选项 ${arg}；使用 --help 查看用法。`);
  }
  if (!/^\d+$/.test(port) || !Number.isSafeInteger(Number(port)) || Number(port) > 65535) throw new Error('--port 必须是 0～65535 的整数。');
  const [major, minor] = process.versions.node.split('.').map(Number);
  if (!((major === 22 && minor >= 16) || major >= 24)) throw new Error('需要 Node.js 22.16+（22.x）或 24+，当前为 ' + process.version);
  if (!['linux', 'darwin'].includes(process.platform)) throw new Error('安装脚本目前支持 Linux 和 macOS。');
  if (deployment === '~' || deployment.startsWith('~/')) deployment = join(homedir(), deployment.slice(2));
  deployment = canonical(resolve(deployment));
  if (contains(source, deployment) || contains(deployment, source)) throw new Error('部署目录必须位于源码目录之外，且不能是源码目录的父目录。');
  if (stat(deployment) && !stat(deployment).isDirectory()) throw new Error('部署路径不是目录。');

  const launcher = join(deployment, 'chatopus'), configFile = join(deployment, 'config.local.json'), envFile = join(deployment, '.env');
  for (const path of [launcher, configFile, envFile]) {
    if (stat(path) && !stat(path).isFile()) throw new Error(`${basename(path)} 必须是普通文件，不能是符号链接。`);
  }
  if (stat(launcher) && !readFileSync(launcher, 'utf8').startsWith('#!/bin/sh\n' + marker + '\n')) {
    throw new Error('已有 chatopus 启动文件不是本安装脚本生成的；请另选部署目录或先自行备份并移开该文件。');
  }
  if (stat(configFile)) {
    try {
      const config = JSON.parse(readFileSync(configFile, 'utf8'));
      if (!config || typeof config !== 'object' || Array.isArray(config)) throw new Error();
    } catch { throw new Error('已有 config.local.json 不是有效的 JSON 配置；未覆盖，请先修复。'); }
  }

  const npm = executable('npm'), rg = executable('rg');
  const env = { ...process.env, PATH: dirname(process.execPath) + delimiter + (process.env.PATH ?? '') };
  run(npm, ['--version'], source, env);
  run(rg, ['--version'], source, env);
  if (!skipDeps) {
    console.log('\n安装锁定版本的依赖（包含运行所需的 tsx）…');
    run(npm, ['ci', '--include=dev'], source, env);
  }
  const tsx = join(source, 'node_modules', 'tsx', 'dist', 'cli.mjs'), cli = join(source, 'src', 'cli.ts');
  try { accessSync(tsx, constants.R_OK); } catch { throw new Error('缺少 tsx 运行依赖，请去掉 --skip-deps 后重新安装。'); }

  mkdirSync(deployment, { recursive: true, mode: 0o700 });
  chmodSync(deployment, 0o700);
  if (!stat(configFile)) {
    const config = JSON.parse(readFileSync(join(source, 'config.example.json'), 'utf8'));
    config.stateDir = join(deployment, 'runtime');
    mkdirSync(config.stateDir, { recursive: true, mode: 0o700 });
    createPrivate(configFile, JSON.stringify(config, null, 2) + '\n');
  } else chmodSync(configFile, 0o600);
  createPrivate(envFile, readFileSync(join(source, '.env.example'), 'utf8'));
  const script = `#!/bin/sh\n${marker}\nset -eu\nexport PATH=${quote(dirname(process.execPath) + delimiter + dirname(rg))}:"\${PATH:-/usr/bin:/bin}"\ncd ${quote(deployment)}\nexec ${quote(process.execPath)} ${quote(tsx)} ${quote(cli)} "$@"\n`;
  const temporary = launcher + '.install-' + process.pid;
  try {
    writeFileSync(temporary, script, { flag: 'wx', mode: 0o700 });
    renameSync(temporary, launcher);
  } finally { rmSync(temporary, { force: true }); }

  console.log('\n检查部署配置（不调用模型、不连接 QQ）…');
  run(launcher, ['doctor'], deployment, env);
  console.log(`\n基础安装完成。配置和数据目录：${deployment}\nRouter / Worker 的模型和密钥可稍后在后台填写。\n启动后台：\n  ${quote(launcher)} admin --port ${Number(port)}\n配置检查：\n  ${quote(launcher)} doctor\n\n源码和 Node 路径改变后，可重新运行本脚本生成启动命令；已有配置和密钥会保留。`);
  if (!startAdmin) return;

  console.log('\n正在启动管理后台，按 Ctrl-C 停止；远程访问方式见 README。');
  const child = spawn(launcher, ['admin', '--port', String(Number(port))], { cwd: deployment, env, stdio: 'inherit' });
  const interrupt = () => child.kill('SIGINT'), terminate = () => child.kill('SIGTERM');
  process.once('SIGINT', interrupt); process.once('SIGTERM', terminate);
  try {
    process.exitCode = await new Promise((resolve, reject) => {
      child.once('error', reject);
      child.once('exit', (code, signal) => resolve(code ?? (signal === 'SIGINT' ? 130 : 1)));
    });
  } finally {
    process.removeListener('SIGINT', interrupt); process.removeListener('SIGTERM', terminate);
  }
}

main().catch(error => { console.error('安装失败：' + error.message); process.exitCode = 1; });
